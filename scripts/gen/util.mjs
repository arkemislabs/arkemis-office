/** kebab-case id from a label: "Table Design" -> "table-design", "Font…" -> "font". */
export function kebab(s) {
  return String(s ?? '')
    .normalize('NFKD').replace(/[̀-ͯ]/g, '')
    .replace(/&/g, ' and ')
    .replace(/['’]/g, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^A-Za-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase() || 'item';
}

export function exists(p) {
  try { fs.accessSync(p); return true; } catch { return false; }
}

/** Recursive, sorted list of files under `dir` whose name passes `filter`. */
export function walk(dir, filter = () => true) {
  const out = [];
  const visit = d => {
    let entries;
    try { entries = fs.readdirSync(d, {withFileTypes: true}); } catch { return; }
    entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    for (const e of entries) {
      const full = path.join(d, e.name);
      if (e.isDirectory()) visit(full);
      else if (e.isFile() && filter(e.name, full)) out.push(full);
    }
  };
  visit(dir);
  return out;
}

export function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8').replace(/^﻿/, ''));
}

/** Write a file only when its content changed (keeps mtimes stable for esbuild and tsc). */
export function writeIfChanged(file, text) {
  try { if (fs.readFileSync(file, 'utf8') === text) return false; } catch { /* new file */ }
  fs.mkdirSync(path.dirname(file), {recursive: true});
  fs.writeFileSync(file, text);
  return true;
}

/** Stable JSON (sorted keys) for deterministic outputs. */
export function stableStringify(value, indent = 2) {
  const sort = v => {
    if (Array.isArray(v)) return v.map(sort);
    if (v && typeof v === 'object') return Object.fromEntries(Object.keys(v).sort().map(k => [k, sort(v[k])]));
    return v;
  };
  return JSON.stringify(sort(value), null, indent);
}

/** RFC 7396 JSON merge patch. */
export function mergePatch(target, patch) {
  if (patch === null || typeof patch !== 'object' || Array.isArray(patch)) return structuredClone(patch);
  const out = target && typeof target === 'object' && !Array.isArray(target) ? {...target} : {};
  for (const [k, v] of Object.entries(patch)) {
    if (v === null) delete out[k];
    else out[k] = mergePatch(out[k], v);
  }
  return out;
}

/** A collector for errors (fail --check) and warnings (spec anomalies, reported). */
export class Report {
  constructor() { this.errors = []; this.warnings = []; this.info = []; }
  error(where, message) { this.errors.push(`${where}: ${message}`); }
  warn(where, message) { this.warnings.push(`${where}: ${message}`); }
  note(where, message) { this.info.push(`${where}: ${message}`); }
}

