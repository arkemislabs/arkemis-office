export function specModule(app, model) {
  const head = `// GENERATED by scripts/generate.mjs from docs/spec (${app}). Do not edit.\nimport type {SpecModel} from './spec-types';\n`;
  if (!model) return `${head}// No spec file: the app keeps its legacy ribbon.\nconst spec: SpecModel | null = null;\nexport default spec;\n`;
  // JSON.parse of one string literal: fast to parse at runtime and cheap for tsc (no giant literal type).
  return `${head}const spec: SpecModel | null = JSON.parse(${JSON.stringify(JSON.stringify(model))});\nexport default spec;\n`;
}
