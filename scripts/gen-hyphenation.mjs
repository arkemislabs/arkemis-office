// Writes core/quill/lib/hyphen-data.mjs from assets/hyphenation/: the Liang pattern files as strings and the US English dictionary as
// base64 of its raw-deflate bytes (the page view and Node tests cannot read files, so the data travels as a module).
//
//   node scripts/gen-hyphenation.mjs
//
// The files are wordcraft 0.13.1's assets/hyphenation (f2dfa0d), unmodified; their licence headers are inside them and
// assets/third-party-licenses/artcraft-reference.txt names them.

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'assets/hyphenation');
const text = f => JSON.stringify(fs.readFileSync(path.join(dir, f), 'utf8'));
const out = `// GENERATED by scripts/gen-hyphenation.mjs from assets/hyphenation/ (wordcraft 0.13.1, f2dfa0d). Do not edit.
// The pattern files keep their licence headers: English (public domain, trained from Grady Ward's Moby Hyphenator II), Polish, Portuguese,
// Italian and German (hyph-utf8, MIT; see the headers).
export const EN_US_PAT = ${text('en-us.pat')};
export const PL_PAT = ${text('pl.pat')};
export const PT_PAT = ${text('pt.pat')};
export const IT_PAT = ${text('it.pat')};
export const DE_PAT = ${text('de.pat')};
/** assets/hyphenation/en-us.dic: raw deflate of "DCHYPH1\\n" and the front-coded word list (base64). */
export const EN_US_DIC_B64 = ${JSON.stringify(fs.readFileSync(path.join(dir, 'en-us.dic')).toString('base64'))};
`;
fs.writeFileSync(path.join(root, 'core/quill/lib/hyphen-data.mjs'), out);
console.log('hyphen-data.mjs', out.length, 'bytes');
