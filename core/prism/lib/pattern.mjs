/** The 8x8 tile of preset `name` (`pct50` for an unknown name). */
export const tile = name => (TILES.find(([n]) => n === name) ?? TILES.find(([n]) => n === 'pct50'))[1];
/** Is cell (x, y) of the tile the foreground? */
export const isFg = (t, x, y) => ((t[y % 8] ?? 0) & (0x80 >> (x % 8))) !== 0;
/** The foreground cells of preset `name` as runs [x, y, length] (cells), for drawing the tile. */
export function runs(name) {
  const t = tile(name), out = [];
  for (let y = 0; y < 8; y++) {
    let x = 0;
    while (x < 8) {
      if (!isFg(t, x, y)) { x += 1; continue; }
      let n = 1;
      while (x + n < 8 && isFg(t, x + n, y)) n += 1;
      out.push([x, y, n]);
      x += n;
    }
  }
  return out;
}
